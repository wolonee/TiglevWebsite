import type { MetadataRoute } from "next";
import { SITE_URL } from "@/lib/seo";

/**
 * Что роботу обходить, а что нет.
 *
 * Главное здесь — закрыть адреса с параметрами. Каждое сочетание фильтров даёт
 * свой адрес (`/?brand=kia&price=…&opt=50`), таких адресов бесконечно много,
 * и содержимое у них почти одинаковое. `canonical` говорит, какую страницу
 * считать главной, но обход всё равно тратится на дубли — а бюджет обхода
 * у сайта конечный, и уходить он должен на 144 посадочные страницы.
 *
 * Осознанный размен: закрытые от обхода адреса робот не читает, а значит не
 * видит и `canonical` на них. Для фильтров это нормально — мы не хотим их
 * в индексе ни в каком виде. Посадочные страницы параметров не имеют
 * и под запрет не попадают.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: [
          // Фильтры каталога: `/*?` — это любой адрес с параметрами.
          "/*?",
          "/admin",
          "/api/",
          "/sign-in",
          "/sign-up",
          // Витрина UI-кита и загрузчик — служебные, в поиске им делать нечего.
          "/ui-kit",
          "/import",
        ],
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
