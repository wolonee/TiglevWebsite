/** Фирменный цвет знака. Кнопка при этом белая — залитые цветом спорили с «Оставить заявку». */
export const MESSENGER_COLORS: Record<string, string> = {
  telegram: "#229ED9",
  // Средний тон градиента из логотипа MAX: он единственный уходит в фиолетовый
  // и отличает кнопку от двух синих соседей.
  max: "#7075DC",
  vk: "#0077FF",
  whatsapp: "#25D366",
  // Тёмный фиолетовый из фирменной палитры Viber: светлый #7360F2 в ряду
  // сливался бы с MAX, который тоже уходит в фиолетовый.
  viber: "#59267C",
};

/** Незнакомый канал из админки рисуем нейтрально, а не наугад чужим цветом. */
export const DEFAULT_MESSENGER_COLOR = "#1f2933";

const MARKS: Record<string, ReactNode> = {
  telegram: <TelegramMark />,
  whatsapp: <WhatsAppMark />,
};

/**
 * Знак канала. Для добавленных из админки его взять неоткуда, поэтому пишем
 * название — короткое слово узнаётся лучше, чем чужой логотип наугад.
 */
export const markOf = (id: string, label: string): ReactNode =>
  MARKS[id] ?? <span className="text-[15px] font-black tracking-tight">{label.toUpperCase()}</span>;

export const colorOf = (id: string): string => MESSENGER_COLORS[id] ?? DEFAULT_MESSENGER_COLOR;
